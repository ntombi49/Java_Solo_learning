// // Ifstatements

// Decision making lets your program choose what to do based on a condition.

// Example in real life:

// IF it is raining
//     take an umbrella
// ELSE
//     wear sunglasses
// Programs work the same way.

// 1️⃣ The if Statement
// Basic syntax:

// if (condition) {
//     // code runs if condition is true
// }
// Example:

// int age = 18;

// if (age >= 18) {
//     System.out.println("You are an adult.");
// }
// What happens
// If age is 18 or more, the message prints.

// Output:

// You are an adult.